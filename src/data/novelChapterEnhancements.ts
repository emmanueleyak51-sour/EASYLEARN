export function getChapterEnhancement(
  novelId: string,
  chapter: NovelChapterGuide
): NovelChapterEnhancement {
  const exact = NOVEL_CHAPTER_ENHANCEMENTS[novelId]?.[chapter.number];
  if (exact) return exact;

  // Deterministic safe fallback (never empty) for any future chapter added to JAMB_WAEC_NOVELS
  return {
    sceneArtworkKey: 'courtyard',
    sceneCaption: `${chapter.title} — key plot turning point for exam recall.`,
    memoryAnchor: chapter.examTrap,
    chapterQuiz: [
      {
        id: `${novelId}-ch${chapter.number}-fallback`,
        examTag: `Chapter ${chapter.number} Check`,
        q: `Which exam takeaway best captures the core focus of "${chapter.title}"?`,
        o: [
          chapter.examTrap,
          'None of the characters experience any conflict in this chapter',
          'The setting shifts permanently to Antarctica',
          'This chapter is excluded from all WAEC and JAMB syllabuses',
        ],
        a: 0,
        explanation: chapter.summary,
        trapNote: chapter.examTrap,
      },
    ],
  };
}
