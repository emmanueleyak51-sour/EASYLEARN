export function getSubjectTutor(subj: SubjectId): SubjectTutorMeta {
  return SUBJECT_TUTOR_REGISTRY[subj] || SUBJECT_TUTOR_REGISTRY.eng;
}

/**
 * Normalizes legacy voice profile names ('math', 'fmath', 'mathLab') and any SubjectId
 * into a canonical tutor configuration.
 */
export function resolveVoiceProfileMeta(profile: string | undefined): {
  voiceName: string;
  stylePrompt: string;
  defaultPersona: string;
  tutorName: string;
} {
  if (profile === 'mathLab') {
    return {
      voiceName: 'Puck',
      stylePrompt:
        'A warm, calm, encouraging master geometry teacher guiding a student step-by-step at a slate chalkboard with natural classroom presence and unhurried precision.',
      defaultPersona: 'You are the Geometry Coach guiding a student step-by-step on EYAK.',
      tutorName: 'Geometry Coach',
    };
  }
  const normalized: SubjectId =
    profile === 'math'
      ? 'maths'
      : profile === 'fmath'
        ? 'fmaths'
        : profile && Object.prototype.hasOwnProperty.call(SUBJECT_TUTOR_REGISTRY, profile)
          ? (profile as SubjectId)
          : 'chem';
  const meta = SUBJECT_TUTOR_REGISTRY[normalized];
  return {
    voiceName: meta.geminiVoice,
    stylePrompt: meta.voiceStyle,
    defaultPersona: `You are ${meta.tutorName}, a clear, encouraging Nigerian ${meta.roleTitle} teaching on EYAK.`,
    tutorName: meta.tutorName,
  };
}
